KIND_CYCLE = ("none", "name", "email", "none", "phone", "address", "order", "payment", "none")
"""PII shape planted in each successive question; "none" keeps some questions clean."""


@dataclass
class Sample:
    """One question with its expected answer, language and owning agent."""

    question: str
    answer: str
    language: str
    intent: str | None
    agent: str


def _email(name: str) -> str:
    ascii_name = name.lower().replace(" ", ".").replace("é", "e")
    return f"{ascii_name}@example.com"


class PiiPlanter:
    """Adds fake PII to some questions and remembers every planted value."""

    def __init__(self, rng: random.Random) -> None:
        """Share the generator's random source, so the output stays deterministic."""
        self.rng = rng
        self.planted: list[dict[str, str]] = []
        self.count = 0

    def plant(self, question: str, intent: str, language: str) -> str:
        """Cycle through PII shapes so every entity type appears in both languages."""
        kind = KIND_CYCLE[self.count % len(KIND_CYCLE)]
        self.count += 1
        if kind == "none":
            return question
        rest = ""
        if kind == "name":
            value, entity = self.rng.choice(NAMES), "PERSON"
        elif kind == "email":
            value, entity = _email(self.rng.choice(NAMES)), "EMAIL_ADDRESS"
        elif kind == "phone":
            value, entity = self.rng.choice(PHONES[language]), "PHONE_NUMBER"
        elif kind == "address":
            (value, rest), entity = self.rng.choice(ADDRESSES[language]), "STREET_ADDRESS"
        elif kind == "order":
            value, entity = f"CMD-{self.rng.randint(10_000_000, 99_999_999)}", "ORDER_ID"
        elif intent == "refund":
            kind, value, entity = "iban", self.rng.choice(IBANS), "IBAN_CODE"
        else:
            kind, value, entity = "card", self.rng.choice(CARDS), "CREDIT_CARD"
        self.planted.append({"text": value, "entity": entity, "language": language})
        return TEMPLATES[language][kind].format(q=question, value=value, rest=rest)


def _otlp_attribute(key: str, value: object) -> dict[str, Any]:
    if isinstance(value, bool):
        encoded: dict[str, Any] = {"boolValue": value}
    elif isinstance(value, int):
        encoded = {"intValue": str(value)}
    elif isinstance(value, float):
        encoded = {"doubleValue": value}
    else:
        encoded = {"stringValue": str(value)}
    return {"key": key, "value": encoded}


def _messages(role: str, text: str) -> str:
    return json.dumps([{"role": role, "parts": [{"type": "text", "content": text}]}])


def _span(
    trace_id: str,
    span_id: str,
    parent: str | None,
    name: str,
    times: tuple[int, int],
    *,
    attributes: list[dict[str, Any]],
    status: dict[str, Any],
    kind: int = 3,
) -> dict[str, Any]:
    span: dict[str, Any] = {
        "traceId": trace_id,
        "spanId": span_id,
        "name": name,
        "kind": kind,
        "startTimeUnixNano": str(times[0]),
        "endTimeUnixNano": str(times[1]),
        "attributes": attributes,
        "status": status,
    }
    if parent:
        span["parentSpanId"] = parent
    return span


def _otel_trace(
    rng: random.Random, index: int, sample: Sample, *, legacy: bool
) -> list[dict[str, Any]]:
    trace_id = f"{rng.getrandbits(128):032x}"
    root_id, coord_id, agent_id, chat_id = (f"{rng.getrandbits(64):016x}" for _ in range(4))
    start = BASE_TIME_NANO + index * 60_000_000_000
    latency_ms = rng.uniform(900, 1600)
    input_tokens, output_tokens = rng.randint(300, 420), rng.randint(40, 90)
    answer = sample.answer
    status: dict[str, Any] = {"code": 1}
    error_type = None
    outcome = "ANSWER" if sample.intent else "DECLINE"
    feedback = rng.choice([1.0, 1.0, 1.0, None, None])
    # Rough production rates: about 3% slow, 3% token-heavy, 4% errors, 8% thumbs-down.
    if index % 33 == 5:
        latency_ms = rng.uniform(28_000, 40_000)
    if index % 37 == 7:
        input_tokens = rng.randint(9_000, 12_000)
    if index % 25 == 3:
        status, error_type, answer = {"code": 2, "message": "upstream timeout"}, "timeout", ""
        outcome = "UNAVAILABLE"
    if index % 12 == 4:
        feedback = -1.0
    end = start + int(latency_ms * 1_000_000)
    root_attrs = [
        _otlp_attribute("http.route", "/chat"),
        _otlp_attribute("enduser.id", f"cust-{rng.randint(10000, 99999)}"),
        _otlp_attribute(
            "url.full", f"https://shop-assistant.internal/chat?user={_email(rng.choice(NAMES))}"
        ),
    ]
    if feedback is not None:
        root_attrs.append(_otlp_attribute("user_feedback.score", feedback))
        if feedback < 0:
            root_attrs.append(
                _otlp_attribute("user_feedback.comment", NEGATIVE_COMMENT[sample.language])
            )
    root = _span(
        trace_id,
        root_id,
        None,
        "POST /chat",
        (start, end + 2_000_000),
        kind=2,
        attributes=root_attrs,
        status=status,
    )
    if legacy:
        chat_attrs = [
            _otlp_attribute("gen_ai.operation.name", "chat"),
            _otlp_attribute("gen_ai.system", "ollama"),
            _otlp_attribute("gen_ai.request.model", "qwen3.5:4b"),
            _otlp_attribute("gen_ai.prompt.0.role", "system"),
            _otlp_attribute(
                "gen_ai.prompt.0.content", "You help customers with products and orders."
            ),
            _otlp_attribute("gen_ai.prompt.1.role", "user"),
            _otlp_attribute("gen_ai.prompt.1.content", sample.question),
            _otlp_attribute("gen_ai.completion.0.role", "assistant"),
            _otlp_attribute("gen_ai.completion.0.content", answer),
            _otlp_attribute("gen_ai.usage.prompt_tokens", input_tokens),
            _otlp_attribute("gen_ai.usage.completion_tokens", output_tokens),
        ]
        if error_type:
            chat_attrs.append(_otlp_attribute("error.type", error_type))
        return [
            root,
            _span(
                trace_id,
                coord_id,
                root_id,
                "chat qwen3.5:4b",
                (start + 1_000_000, end),
                attributes=chat_attrs,
                status=status,
            ),
        ]
    coord_attrs = [
        _otlp_attribute("gen_ai.operation.name", "invoke_agent"),
        _otlp_attribute("gen_ai.provider.name", "gcp.gemini"),
        _otlp_attribute("gen_ai.request.model", "gemini-2.5-flash"),
        _otlp_attribute("gen_ai.conversation.id", f"ctx-{index:04d}"),
        _otlp_attribute("gen_ai.input.messages", _messages("user", sample.question)),
        _otlp_attribute("gen_ai.output.messages", _messages("assistant", answer)),
        _otlp_attribute("gen_ai.usage.input_tokens", input_tokens),
        _otlp_attribute("gen_ai.usage.output_tokens", output_tokens),
        _otlp_attribute("agent_mesh.outcome", outcome),
    ]
    if error_type:
        coord_attrs.append(_otlp_attribute("error.type", error_type))
    specialist = f"{sample.agent}_agent"
    return [
        root,
        _span(
            trace_id,
            coord_id,
            root_id,
            "invoke_agent coordinator",
            (start + 1_000_000, end),
            attributes=coord_attrs,
            status=status,
        ),
        _span(
            trace_id,
            agent_id,
            coord_id,
            f"invoke_agent {specialist}",
            (start + 3_000_000, end - 3_000_000),
            status=status,
            attributes=[
                _otlp_attribute("gen_ai.operation.name", "invoke_agent"),
                _otlp_attribute("gen_ai.provider.name", "gcp.gemini"),
                _otlp_attribute(
                    "gen_ai.input.messages", _messages("user", f"Delegated to {specialist}")
                ),
            ],
        ),
        _span(
            trace_id,
            chat_id,
            agent_id,
            "chat gemini-2.5-flash",
            (start + 5_000_000, end - 5_000_000),
            status=status,
            attributes=[
                _otlp_attribute("gen_ai.operation.name", "chat"),
                _otlp_attribute("gen_ai.provider.name", "gcp.gemini"),
                _otlp_attribute(
                    "gen_ai.input.messages", _messages("user", "internal retrieval prompt")
                ),
            ],
        ),
    ]


def _batch(spans: list[dict[str, Any]]) -> dict[str, Any]:
    return {
        "resourceSpans": [
            {
                "resource": {"attributes": [_otlp_attribute("service.name", "shop-assistant")]},
                "scopeSpans": [{"scope": {"name": "shop-assistant"}, "spans": spans}],
            }
        ]
    }


def _samples(
    rng: random.Random, planter: PiiPlanter, *, repeats: int = 1, limit: int | None = None
) -> list[Sample]:
    """Shuffle, keep `limit` items, then plant PII.

    `repeats` sends each phrasing several times, as real traffic does, so intents
    form clusters. Planting after the cut keeps the ground truth limited to values
    that are emitted.
    """
    raw: list[Sample] = []
    for intent, (agent, languages) in INTENTS.items():
        for language, (questions, answer) in languages.items():
            raw.extend(
                Sample(q, answer, language, intent, agent)
                for q in questions
                for _ in range(repeats)
            )
    for language, pairs in OFF_TOPIC.items():
        raw.extend(Sample(q, a, language, None, "coordinator") for q, a in pairs)
    rng.shuffle(raw)
    kept = raw[:limit]
    for sample in kept:
        if sample.intent:
            sample.question = planter.plant(sample.question, sample.intent, sample.language)
    return kept


def _mlflow_trace(rng: random.Random, index: int, sample: Sample) -> dict[str, Any]:
    state = "ERROR" if index % 7 == 6 else "OK"
    assessments: list[dict[str, Any]] = []
    if index % 4 == 1:
        negative = index % 8 == 1
        assessments.append(
            {
                "assessment_name": "user_satisfaction",
                "source": {"source_type": "HUMAN", "source_id": f"user-{index}"},
                "feedback": {"value": not negative},
                "rationale": NEGATIVE_COMMENT[sample.language] if negative else "Helpful",
            }
        )
    return {
        "info": {
            "trace_id": f"tr-{rng.getrandbits(96):024x}",
            "client_request_id": f"session-{index:03d}",
            "trace_location": {
                "type": "MLFLOW_EXPERIMENT",
                "mlflow_experiment": {"experiment_id": "1"},
            },
            "request_preview": json.dumps({"question": sample.question}, ensure_ascii=False),
            "response_preview": json.dumps(
                sample.answer if state == "OK" else "", ensure_ascii=False
            ),
            "request_time": f"2026-10-0{1 + index % 9}T09:{index % 60:02d}:00Z",
            "execution_duration_ms": rng.randint(800, 1700),
            "state": state,
            "trace_metadata": {},
            "tags": {},
            "assessments": assessments,
        },
        "data": {"spans": []},
    }


def _write_jsonl(path: Path, items: list[dict[str, Any]]) -> None:
    lines = (json.dumps(item, separators=(",", ":"), ensure_ascii=False) for item in items)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def generate(out_dir: Path) -> None:
    """Write all sample files into `out_dir`."""
    rng = random.Random(SEED)
    planter = PiiPlanter(rng)
    out_dir.mkdir(parents=True, exist_ok=True)

    batches: list[dict[str, Any]] = []
    spans: list[dict[str, Any]] = []
    for index, sample in enumerate(_samples(rng, planter, repeats=OTEL_REPEATS)):
        spans.extend(_otel_trace(rng, index, sample, legacy=index % 9 == 8))
        if (index + 1) % TRACES_PER_BATCH == 0:
            batches.append(_batch(spans))
            spans = []
    if spans:
        batches.append(_batch(spans))
    _write_jsonl(out_dir / "otel_traces.jsonl", batches)

    mlflow = [_mlflow_trace(rng, i, s) for i, s in enumerate(_samples(rng, planter, limit=15))]
    _write_jsonl(out_dir / "mlflow_traces.jsonl", mlflow)

    existing = [
        {
            "id": "shop-0001",
            "topic": "Order tracking",
            "input_text": "Where is my order?",
            "expected_category": "order_tracking",
        },
        {
            "id": "shop-0002",
            "topic": "Retours",
            "input_text": "Comment retourner un article ?",
            "expected_category": "returns",
        },
    ]
    (out_dir / "existing_golden.json").write_text(
        json.dumps(existing, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    (out_dir / "pii_ground_truth.json").write_text(
        json.dumps(planter.planted, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )


if __name__ == "__main__":
    generate(DATA_DIR)
